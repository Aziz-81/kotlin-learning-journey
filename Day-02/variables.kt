// Day 02: Variables and Data Types
fun main() {
    val name: String = "আজিজুল ইসলাম"
    val age: Int = 31
    val education: String = "আরবীতে মাস্টার্স"
    val grade: Double = 4.8
    val dream: String = "প্রফেশনাল এন্ড্রয়েড ডেভেলপার হওয়া"

    println("নাম: $name")
    println("বয়স: $age")
    println("শিক্ষা: $education")
    println("গ্রেড: $grade")
    println("স্বপ্ন: $dream")
}
